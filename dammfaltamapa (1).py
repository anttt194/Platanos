def kpis(route, clients, assign_df, rejected, label, fecha, ruta):
    return {
        'demo': label,
        'fecha': fecha,
        'ruta': ruta,
        'clientes': int(clients.shape[0]),
        'lineas_pedido': int(route.shape[0]),
        'piezas_pedido': int(route['cantidad'].sum()),
        'peso_total_estimado_kg': round(float(route['peso_total'].sum()),2),
        'volumen_total_estimado': round(float(route['volumen_total'].sum()),2),
        'posiciones_camion': TRUCK['total_positions'],
        'posiciones_ocupadas': int(assign_df.shape[0]),
        'ocupacion_pct': round(100*assign_df.shape[0]/TRUCK['total_positions'],2),
        'piezas_no_asignadas': int(rejected.shape[0]),
        'cajas_asignadas': int((assign_df['tipo_producto']=='caja').sum()) if not assign_df.empty else 0,
        'barriles_asignados': int((assign_df['tipo_producto']=='barril').sum()) if not assign_df.empty else 0,
        'retornables_asignados': int((assign_df['tipo_producto']=='retornable').sum()) if not assign_df.empty else 0,
    }


def recomendaciones(k):
    rec=[]
    rec.append('Cargar primero Zona C/R (últimas paradas y retornables) para que quede más al fondo.')
    rec.append('Dejar Zona A en columnas laterales 1 y 6 para descarga rápida de primeras paradas.')
    if k['barriles_asignados']>0: rec.append('Colocar barriles/bidones en posiciones accesibles y tratarlos como doble ocupación por peso/volumen.')
    if k['retornables_asignados']>0: rec.append('Reservar capacidad para retornables durante la ruta.')
    if k['piezas_no_asignadas']>0: rec.append('ALERTA: la ruta supera la capacidad visual del camión 6P; revisar fraccionamiento o vehículo mayor.')
    else: rec.append('OK: toda la carga demo cabe en la capacidad visual modelada.')
    return rec


def run_demo():
    deliveries, materials, horarios, zubic = read_data(DATA_DIR)
    mat = prepare_material_master(materials)
    all_kpis=[]
    excel_outputs={}
    for cfg in DEMO_ROUTES:
        fecha,ruta,label=cfg['fecha'],cfg['ruta'],cfg['label']
        route, clients = build_route_dataset(deliveries, mat, horarios, zubic, fecha, ruta)
        items = expand_items(route)
        assign_df, positions, rejected = assign_to_truck(items)
        kp = kpis(route, clients, assign_df, rejected, label, fecha, ruta)
        kp['recomendaciones'] = ' | '.join(recomendaciones(kp))
        all_kpis.append(kp)
        stem=f"{ruta}_{fecha}"
        # outputs
        route.to_csv(OUTPUT_DIR/f'{stem}_datos_enlazados.csv', index=False)
        clients.to_csv(OUTPUT_DIR/f'{stem}_secuencia_clientes.csv', index=False)
        assign_df.to_csv(OUTPUT_DIR/f'{stem}_asignacion_camion.csv', index=False)
        positions.to_csv(OUTPUT_DIR/f'{stem}_posiciones_camion.csv', index=False)
        rejected.to_csv(OUTPUT_DIR/f'{stem}_piezas_no_asignadas.csv', index=False)
        make_2d(assign_df, f'{label} - {ruta} {fecha} - Plano 2D').write_html(OUTPUT_DIR/f'{stem}_plano_2d.html')
        make_3d(assign_df, positions, f'{label} - {ruta} {fecha} - Plano 3D').write_html(OUTPUT_DIR/f'{stem}_plano_3d.html')
        excel_outputs[f'{stem}_clientes'] = clients
        excel_outputs[f'{stem}_kpi'] = pd.DataFrame([kp])
        print(f"Generado {stem}: clientes={kp['clientes']}, ocupación={kp['ocupacion_pct']}%, no asignadas={kp['piezas_no_asignadas']}")
    summary=pd.DataFrame(all_kpis)
    summary.to_csv(OUTPUT_DIR/'resumen_3_rutas_demo.csv', index=False)
    with pd.ExcelWriter(OUTPUT_DIR/'resumen_3_rutas_demo.xlsx', engine='openpyxl') as writer:
        summary.to_excel(writer, sheet_name='KPIs', index=False)
        for sh,df in excel_outputs.items():
            df.head(500).to_excel(writer, sheet_name=sh[:31], index=False)
    return summary

if __name__ == '__main__':
    summary = run_demo()
    print('\n=== RESUMEN 3 RUTAS ===')
    print(summary.to_string(index=False))

