    fig.update_layout(title=title,scene=dict(xaxis=dict(title='Columnas',range=[0,7.8],dtick=1),yaxis=dict(title='Filas',range=[-2,14],dtick=1),zaxis=dict(title='Altura',range=[0,6],dtick=1),aspectmode='manual',aspectratio=dict(x=1.1,y=2.2,z=0.8),camera=dict(eye=dict(x=1.6,y=-2.1,z=1.3))),width=1100,height=800,margin=dict(l=0,r=0,t=60,b=0))
