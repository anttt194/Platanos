def time_windows_compatible(group):
    if not REQUIRE_TIME_WINDOW_OVERLAP:
        return True
    start=max([g['hora_inicio_min'] for g in group])
    end=min([g['hora_fin_min'] for g in group])
    return start <= end


def medoid_client(group):
    best=None; best_sum=1e18
    for cand in group:
        s=sum(distance_m(cand, other) for other in group)
        if s<best_sum:
            best_sum=s; best=cand
    return best


def build_stops(clients, clustered=True, radius_m=CLUSTER_RADIUS_M):
    records=[r.to_dict() for _,r in clients.iterrows()]
    if not clustered or radius_m<=0:
        stops=[]
        for i,r in enumerate(records):
            stops.append({
                'stop_id':f'S{i+1}', 'clients':[r], 'lat':r['lat'], 'lng':r['lng'], 'parking_client_key':r['cliente_key'],
                'piezas':r['piezas'], 'lineas':r['lineas'], 'hora_inicio_min':r['hora_inicio_min'], 'hora_fin_min':r['hora_fin_min'],
                'service_time_min':r['service_time_min'], 'walking_time_min':0.0, 'n_clients':1
            })
        return pd.DataFrame(stops)

    unassigned=set(range(len(records)))
    stops=[]
    while unassigned:
        # escollim primer el client amb finestra més urgent
        seed=min(unassigned, key=lambda i: records[i]['hora_fin_min'])
        group=[records[seed]]
        unassigned.remove(seed)
        # candidats propers al seed, ordenats per distància
        candidates=sorted(list(unassigned), key=lambda i: distance_m(records[seed], records[i]))
        for ci in candidates:
            if len(group)>=MAX_CLIENTS_PER_STOP: break
            cand=records[ci]
            if distance_m(records[seed], cand)>radius_m: continue
            tentative=group+[cand]
            if sum(g['piezas'] for g in tentative)>MAX_PIECES_PER_STOP: continue
            if not time_windows_compatible(tentative): continue
            # tots relativament propers al medoid candidat
            group=tentative
            unassigned.remove(ci)
        med=medoid_client(group)
        walking_m=sum(2*distance_m(med,g) for g in group if g['cliente_key']!=med['cliente_key'])
        walking_time=walking_m/WALK_SPEED_M_PER_MIN
        stops.append({
            'stop_id':f'S{len(stops)+1}', 'clients':group, 'lat':med['lat'], 'lng':med['lng'], 'parking_client_key':med['cliente_key'],
            'piezas':sum(g['piezas'] for g in group), 'lineas':sum(g['lineas'] for g in group),
            'hora_inicio_min':max(g['hora_inicio_min'] for g in group), 'hora_fin_min':min(g['hora_fin_min'] for g in group),
            'service_time_min':sum(g['service_time_min'] for g in group)+walking_time,
            'walking_time_min':walking_time, 'walking_m':walking_m, 'n_clients':len(group)
        })
    return pd.DataFrame(stops)

