def load_cache():
    if CACHE_FILE.exists(): return pd.read_csv(CACHE_FILE)
    return pd.DataFrame(columns=['address_key','query','lat','lng','display_name','status'])


def geocode_query(q):
    params={'q':q,'format':'json','limit':1,'countrycodes':'es'}
    headers={'User-Agent':USER_AGENT}
    try:
        r=requests.get(NOMINATIM_URL,params=params,headers=headers,timeout=15)
        if r.status_code!=200: return None,None,'',f'HTTP_{r.status_code}'
        data=r.json()
        if not data: return None,None,'','NO_ENCONTRADO'
        item=data[0]
        return float(item['lat']),float(item['lon']),item.get('display_name',''),'OK'
    except Exception as e:
        return None,None,'','ERROR_'+type(e).__name__


def geocode_all(clients):
    cache=load_cache()
    cache_map={row['address_key']:row for _,row in cache.iterrows()}
    rows=[]; new_rows=[]
    unique=clients[['query_address']].drop_duplicates().copy()
    unique['address_key']=unique['query_address'].apply(address_key)
    for _,a in unique.iterrows():
        key,q=a['address_key'],a['query_address']
        if key in cache_map:
            row=cache_map[key]
            rows.append({'address_key':key,'query':q,'lat':row.get('lat'),'lng':row.get('lng'),'display_name':row.get('display_name',''),'status':row.get('status','')})
        else:
            print('Geocodificant:',q)
            lat,lng,disp,status=geocode_query(q)
            row={'address_key':key,'query':q,'lat':lat,'lng':lng,'display_name':disp,'status':status}
            rows.append(row); new_rows.append(row)
            time.sleep(1.1)
    if new_rows:
        cache=pd.concat([cache,pd.DataFrame(new_rows)],ignore_index=True).drop_duplicates('address_key',keep='last')
        cache.to_csv(CACHE_FILE,index=False)
    geo=pd.DataFrame(rows).drop_duplicates('address_key')
    out=clients.copy()
    out['address_key']=out['query_address'].apply(address_key)
    out=out.merge(geo,on='address_key',how='left')
    out['lat']=pd.to_numeric(out['lat'],errors='coerce')
    out['lng']=pd.to_numeric(out['lng'],errors='coerce')
    out['coord_ok']=out['lat'].between(40.0,43.5)&out['lng'].between(0.0,4.0)
    out['geocode_valid']=out['status'].eq('OK')&out['coord_ok']
    out.to_csv(OUT/'geocoding_validacion.csv',index=False)
    return out

