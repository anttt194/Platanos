def clean_cp(cp):
    try:
        return str(int(float(cp))).zfill(5)
    except Exception:
        return str(cp).strip().zfill(5)


def parse_time_to_minutes(x, default=None):
    try:
        if pd.isna(x): return default
        if isinstance(x, str):
            txt=x.strip()
            if txt=='': return default
            if ':' in txt:
                h,m=txt.split(':')[:2]
                return int(h)*60+int(m)
            val=float(txt)
        else:
            val=float(x)
        if 0 < val < 1: return int(round(val*24*60))
        if val <= 24: return int(round(val*60))
        return int(round(val))
    except Exception:
        return default


def hhmm(m):
    if pd.isna(m): return ''
    m=int(round(m))
    return f'{(m//60)%24:02d}:{m%60:02d}'


def haversine_km(lat1, lon1, lat2, lon2):
    R=6371.0
    p1,p2=math.radians(lat1),math.radians(lat2)
    dp=math.radians(lat2-lat1)
    dl=math.radians(lon2-lon1)
    a=math.sin(dp/2)**2 + math.cos(p1)*math.cos(p2)*math.sin(dl/2)**2
    return 2*R*math.asin(math.sqrt(a))


def distance_m(a, b):
    return 1000*haversine_km(a['lat'], a['lng'], b['lat'], b['lng'])


def address_key(q):
    return hashlib.sha1(q.lower().encode('utf-8')).hexdigest()


def build_address(row):
    return f"{row['calle']}, {row['cp']}, {row['poblacion']}, Barcelona, España"


def travel_time_min(km):
    return km / AVG_SPEED_KMH * 60

