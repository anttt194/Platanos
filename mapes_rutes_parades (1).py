def run_clustering_optimizer():
    deliveries,horarios=load_files()
    all_clients=[]; route_lines={}
    for cfg in DEMO_ROUTES:
        c,l=extract_clients(deliveries,horarios,cfg['fecha'],cfg['ruta'],cfg['label'])
        all_clients.append(c); route_lines[(cfg['fecha'],cfg['ruta'])]=l
    all_geo=geocode_all(pd.concat(all_clients,ignore_index=True))
    summary=[]
    for cfg in DEMO_ROUTES:
        fecha,ruta,label=cfg['fecha'],cfg['ruta'],cfg['label']
        cr=all_geo[(all_geo['route_fecha']==fecha)&(all_geo['route_code']==ruta)].copy()
        valid=cr[cr['geocode_valid']].copy().reset_index(drop=True)
        invalid=cr[~cr['geocode_valid']].copy()
        if valid.empty: raise ValueError(f'Cap client geocodificat vàlid per {ruta} {fecha}')

        # baseline: 1 client = 1 parada
        base_stops=build_stops(valid,clustered=False)
        base_order=two_opt_stops(greedy_stop_route(base_stops),base_stops)
        base_stop_df,base_client_df=validate_stop_route(base_order,base_stops,ruta,fecha,'baseline')
        base_cost,base_km,base_late,base_walk=stop_route_cost(base_order,base_stops)

        # clustered: clients propers en 1 parada
        cl_stops=build_stops(valid,clustered=True,radius_m=CLUSTER_RADIUS_M)
        cl_order=two_opt_stops(greedy_stop_route(cl_stops),cl_stops)
        cl_stop_df,cl_client_df=validate_stop_route(cl_order,cl_stops,ruta,fecha,'clustered')
        cl_cost,cl_km,cl_late,cl_walk=stop_route_cost(cl_order,cl_stops)

        # decisió automàtica: només usem clustering si millora cost i no empitjora retards
        use_clustered=(cl_cost<base_cost) and (cl_late<=base_late+1e-6)
        chosen='clustered' if use_clustered else 'baseline'
        stop_df=cl_stop_df if use_clustered else base_stop_df
        client_df=cl_client_df if use_clustered else base_client_df
        cost=cl_cost if use_clustered else base_cost

        stem=f'{ruta}_{fecha}'
        base_stop_df.to_csv(OUT/f'{stem}_baseline_parades.csv',index=False)
        base_client_df.to_csv(OUT/f'{stem}_baseline_clients.csv',index=False)
        cl_stop_df.to_csv(OUT/f'{stem}_clustered_parades.csv',index=False)
        cl_client_df.to_csv(OUT/f'{stem}_clustered_clients.csv',index=False)
        stop_df.to_csv(OUT/f'{stem}_BEST_parades.csv',index=False)
