import math
import numpy as np
import plotly.graph_objects as go
import requests
import polyline

VISUAL_OFFSET_M = 12  # només visual; no modifica coordenades reals ni CSVs


def _offset_latlng(lat, lng, meters, angle_rad):
    dlat = (meters * math.sin(angle_rad)) / 111_320
    dlng = (meters * math.cos(angle_rad)) / (111_320 * math.cos(math.radians(lat)))
    return lat + dlat, lng + dlng


def generate_cluster_map(stop_df, client_df, label, html_path):
    fig = go.Figure()

    # Ruta del camió: origen -> parades -> origen
    points = [{'lat': ORIGEN['lat'], 'lng': ORIGEN['lng'], 'label': 'ORIGEN'}]

    for _, r in stop_df.sort_values('stop_order').iterrows():
        points.append({
            'lat': r['lat'],
            'lng': r['lng'],
            'label': f"S{int(r['stop_order'])}"
        })

    points.append({
        'lat': ORIGEN['lat'],
        'lng': ORIGEN['lng'],
        'label': 'FIN'
    })

    coords = ';'.join([f"{p['lng']},{p['lat']}" for p in points])

    try:
        res = requests.get(
            f"https://router.project-osrm.org/route/v1/driving/{coords}?overview=full&geometries=polyline",
            timeout=15
        ).json()

        path = polyline.decode(res['routes'][0]['geometry'])
        lats, lons = zip(*path)

        fig.add_trace(go.Scattermapbox(
            lat=lats,
            lon=lons,
            mode='lines',
            line=dict(width=4, color='#004B87'),
            name='Ruta camió OSRM'
        ))

    except Exception:
        fig.add_trace(go.Scattermapbox(
            lat=[p['lat'] for p in points],
            lon=[p['lng'] for p in points],
            mode='lines',
            line=dict(width=4, color='#004B87'),
            name='Ruta camió visual'
        ))

    # Copiem els locals per aplicar offset només visual
    client_plot = client_df.copy().sort_values(
        ['stop_order', 'sub_stop_order']
    ).reset_index(drop=True)

    plot_lats = []
    plot_lngs = []

    for _, c in client_plot.iterrows():
        siblings = client_plot[client_plot['stop_id'] == c['stop_id']]
        n = max(1, len(siblings))
        k = int(c['sub_stop_order']) - 1

        angle = 2 * math.pi * k / n

        lat_v, lng_v = _offset_latlng(
            float(c['lat']),
            float(c['lng']),
            VISUAL_OFFSET_M,
            angle
        )

        plot_lats.append(lat_v)
        plot_lngs.append(lng_v)

    client_plot['plot_lat'] = plot_lats
    client_plot['plot_lng'] = plot_lngs

    # Línies grises parada -> local
    for _, s in stop_df.iterrows():
        sub = client_plot[client_plot['stop_id'] == s['stop_id']]

        for _, c in sub.iterrows():
            fig.add_trace(go.Scattermapbox(
                lat=[s['lat'], c['plot_lat']],
                lon=[s['lng'], c['plot_lng']],
                mode='lines',
                line=dict(width=1, color='gray'),
                hoverinfo='skip',
                showlegend=False
            ))

    # Parades del camió, en blau
    fig.add_trace(go.Scattermapbox(
        lat=stop_df['lat'],
        lon=stop_df['lng'],
        mode='markers+text',
        marker=dict(size=18, color='#004B87', opacity=0.65),
        text=[f"S{int(r.stop_order)}" for _, r in stop_df.iterrows()],
        textposition='top right',
        hovertext=[
            f"<b>Parada camió S{int(r.stop_order)}</b><br>"
            f"Locals en aquesta parada: {int(r.n_clients)}<br>"
            f"Peces totals: {int(r.piezas)}<br>"
            f"Walking: {r.walking_time_min} min<br>"
            f"Status: {r.status}"
            for _, r in stop_df.iterrows()
        ],
        hoverinfo='text',
        name='Parades camió'
    ))

    # Locals, en vermell, dibuixats DESPRÉS perquè quedin per sobre
    fig.add_trace(go.Scattermapbox(
        lat=client_plot['plot_lat'],
        lon=client_plot['plot_lng'],
        mode='markers+text',
        marker=dict(size=10, color='#E2231A', opacity=0.95),
        text=[
            f"{int(r.stop_order)}.{int(r.sub_stop_order)}"
            for _, r in client_plot.iterrows()
        ],
        textposition='bottom right',
        hovertext=[
            f"<b>Local {int(r.stop_order)}.{int(r.sub_stop_order)}</b><br>"
            f"{r.nombre}<br>"
            f"{r.direccion}<br>"
            f"Parada camió: S{int(r.stop_order)}<br>"
            f"Peces: {int(r.piezas)} | Línies: {int(r.lineas)}"
            for _, r in client_plot.iterrows()
        ],
        hoverinfo='text',
        name='Locals / establiments'
    ))

    # Origen
    fig.add_trace(go.Scattermapbox(
        lat=[ORIGEN['lat']],
        lon=[ORIGEN['lng']],
        mode='markers+text',
        marker=dict(size=15, color='black'),
        text=['ORIGEN'],
        textposition='top left',
        hovertext=['DDI Fàbrica Mollet'],
        hoverinfo='text',
        name='Origen'
    ))

    center_lat = np.mean(list(stop_df['lat']) + [ORIGEN['lat']])
    center_lng = np.mean(list(stop_df['lng']) + [ORIGEN['lng']])

    n_clients = len(client_plot)
    n_stops = len(stop_df)

    fig.update_layout(
        mapbox=dict(
            style='carto-positron',
            center=dict(lat=center_lat, lon=center_lng),
            zoom=12.5
        ),
        margin={'r': 0, 't': 85, 'l': 0, 'b': 0},
        title=(
            f"<b>{label}</b><br>"
            f"<sup>{n_stops} parades de camió | {n_clients} locals representats | "
            f"S = parada, x.y = local dins parada</sup>"
        ),
        width=1100,
        height=820,
    )

    fig.write_html(html_path)
    return fig


