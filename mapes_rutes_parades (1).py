def greedy_stop_route(stops):
    pending=set(stops.index.tolist()); order=[]
    cur_lat,cur_lng=ORIGEN['lat'],ORIGEN['lng']; cur_time=START_TIME_MIN
    while pending:
        cand=[]
        for idx in pending:
            s=stops.loc[idx]
            dist=haversine_km(cur_lat,cur_lng,s['lat'],s['lng']); tt=travel_time_min(dist); arr=cur_time+tt
            late=max(0,arr-s['hora_fin_min']); urgency=max(0,s['hora_fin_min']-arr)/60
            score=ALPHA_TRAVEL*tt+BETA_LATE*late+GAMMA_URGENCY*urgency+DELTA_SERVICE*s['service_time_min']
            cand.append((score,idx,arr))
        _,idx,arr=sorted(cand,key=lambda x:x[0])[0]
        order.append(idx); pending.remove(idx)
        s=stops.loc[idx]
        cur_time=max(arr,s['hora_inicio_min'])+s['service_time_min']; cur_lat,cur_lng=s['lat'],s['lng']
    return order


def stop_route_cost(order, stops):
    cur_lat,cur_lng=ORIGEN['lat'],ORIGEN['lng']; cur_time=START_TIME_MIN
    dist_total=late_total=walk_total=0.0
    for idx in order:
        s=stops.loc[idx]
        dist=haversine_km(cur_lat,cur_lng,s['lat'],s['lng']); arr=cur_time+travel_time_min(dist)
        late_total+=max(0,arr-s['hora_fin_min']); dist_total+=dist; walk_total+=s['walking_time_min']
        cur_time=max(arr,s['hora_inicio_min'])+s['service_time_min']; cur_lat,cur_lng=s['lat'],s['lng']
    dist_total+=haversine_km(cur_lat,cur_lng,ORIGEN['lat'],ORIGEN['lng'])
    cost=COST_DISTANCE*dist_total+COST_LATE*late_total+COST_STOPS*len(order)+COST_WALKING*walk_total
    return cost,dist_total,late_total,walk_total


def two_opt_stops(order, stops, max_iter=200):
    best=order[:]; best_cost,_,best_late,_=stop_route_cost(best,stops)
    improved=True; it=0
    while improved and it<max_iter:
        improved=False; it+=1
        for i in range(0,len(best)-2):
            for j in range(i+2,len(best)):
                cand=best[:i]+list(reversed(best[i:j]))+best[j:]
                c,_,late,_=stop_route_cost(cand,stops)
                if c<best_cost and late<=best_late:
                    best,best_cost,best_late=cand,c,late; improved=True; break
            if improved: break
    return best


def validate_stop_route(order, stops, ruta, fecha, scenario):
    stop_rows=[]; client_rows=[]; cur_lat,cur_lng=ORIGEN['lat'],ORIGEN['lng']; cur_time=START_TIME_MIN; acc=0.0
    for stop_order,idx in enumerate(order,1):
        s=stops.loc[idx]
        dist=haversine_km(cur_lat,cur_lng,s['lat'],s['lng']); tt=travel_time_min(dist); arr=cur_time+tt
        wait=max(0,s['hora_inicio_min']-arr); late=max(0,arr-s['hora_fin_min'])
        dep=arr+wait+s['service_time_min']; acc+=dist
        stop_rows.append({'scenario':scenario,'route_code':ruta,'fecha':fecha,'stop_order':stop_order,'stop_id':s['stop_id'],'lat':s['lat'],'lng':s['lng'],'n_clients':s['n_clients'],'piezas':s['piezas'],'lineas':s['lineas'],'parking_client_key':s['parking_client_key'],'walking_time_min':round(s['walking_time_min'],1),'walking_m':round(s.get('walking_m',0),1),'hora_inicio_stop':hhmm(s['hora_inicio_min']),'hora_fin_stop':hhmm(s['hora_fin_min']),'travel_km':round(dist,3),'arrival_time':hhmm(arr),'departure_time':hhmm(dep),'late_minutes':round(late,1),'distance_accum_km':round(acc,3),'status':'TARDE' if late>0 else 'OK'})
        # ordre intern: primer el medoid/aparcament, després més propers
        clients=sorted(s['clients'], key=lambda c: distance_m({'lat':s['lat'],'lng':s['lng']}, c))
        for sub_i,c in enumerate(clients,1):
            client_rows.append({'scenario':scenario,'route_code':ruta,'fecha':fecha,'stop_order':stop_order,'sub_stop_order':sub_i,'stop_id':s['stop_id'],'cliente_key':c['cliente_key'],'nombre':c['nombre'],'direccion':c['query_address'],'lat':c['lat'],'lng':c['lng'],'piezas':c['piezas'],'lineas':c['lineas'],'is_parking_point':c['cliente_key']==s['parking_client_key']})
        cur_time=dep; cur_lat,cur_lng=s['lat'],s['lng']
    return pd.DataFrame(stop_rows), pd.DataFrame(client_rows)

