def load_files():
    missing=[f for f in ['Hackaton.xlsx','Horarios Entrega.XLSX'] if not Path(f).exists()]
    if missing:
        raise FileNotFoundError('Falten fitxers: '+', '.join(missing)+'. Puja-los al panell Files de Colab.')
    deliveries=pd.read_excel('Hackaton.xlsx', sheet_name='Detalle entrega', engine='openpyxl')
    horarios=pd.read_excel('Horarios Entrega.XLSX', sheet_name='Sheet1', engine='openpyxl')
    return deliveries, horarios


def prepare_horarios(horarios):
    h=horarios.copy()
    h['cliente_key']=h['Deudor'].astype(str).str.replace('.0','',regex=False).str.strip()
    h['hora_inicio_min']=h['Horario inicia a'].apply(lambda x: parse_time_to_minutes(x, default=START_TIME_MIN))
    h['hora_fin_min']=h['Horario termina a'].apply(lambda x: parse_time_to_minutes(x, default=18*60))
    return h[['cliente_key','hora_inicio_min','hora_fin_min']].drop_duplicates('cliente_key')


def extract_clients(deliveries, horarios, fecha, ruta, label):
    df=deliveries.copy()
    df['FECHA_dt']=pd.to_datetime(df['FECHA'], errors='coerce', dayfirst=True)
    df['FECHA_str']=df['FECHA_dt'].dt.strftime('%Y-%m-%d')
    df['Ruta']=df['Ruta'].astype(str).str.strip()
    df['Población']=df['Población'].astype(str).str.strip()
    df['cliente_key']=df['Destinatario mcía..1'].astype(str).str.replace('.0','',regex=False).str.strip()
    df['cantidad']=pd.to_numeric(df['Cantidad entrega'], errors='coerce').fillna(0)
    route_lines=df[(df['FECHA_str']==fecha)&(df['Ruta']==ruta)].copy()
    if route_lines.empty:
        raise ValueError(f'No hi ha dades per {ruta} {fecha}')
    clients=route_lines.groupby('cliente_key').agg(
        nombre=('Nombre 1','first'), calle=('Calle','first'), cp=('CP','first'), poblacion=('Población','first'),
        piezas=('cantidad','sum'), lineas=('Material','size')
    ).reset_index()
    clients['cp']=clients['cp'].apply(clean_cp)
    clients['query_address']=clients.apply(build_address, axis=1)
    h=prepare_horarios(horarios)
    clients=clients.merge(h,on='cliente_key',how='left')
    clients['hora_inicio_min']=clients['hora_inicio_min'].fillna(START_TIME_MIN)
    clients['hora_fin_min']=clients['hora_fin_min'].fillna(18*60)
    clients['service_time_min']=PARKING_TIME_MIN + SERVICE_PER_PIECE_MIN*clients['piezas'] + SERVICE_PER_LINE_MIN*clients['lineas']
    clients['route_code']=ruta; clients['route_fecha']=fecha; clients['route_label']=label
    return clients, route_lines

